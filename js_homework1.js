'number' + 3 + 3 //конкатенація, стрінг додається до суми намберів - number33

null + 3 // так розумію, що нал перетвоюється неявно до нуля, тому в аутпуті сума - 3

5 && "qwerty" // ось тут цікаво: ліве значення дає тру, тому далі виконується праве значення - стрінг, що також дає тру, в аутпуті - qwerty;  якщо б перше значення давало фолс, то виконання завершилось і вивелось - false або значення, що дає фолс

+'40' + +'2' + "hillel";  // перша стрінг і друга стрінг явно перетворюються до намбера, далі відбувається конкатенація зі третьою стрінгою - 42hillel

'10' - 5 === 6; //пріорітет виконання оператоів арифметичних над порівнянням, неявне перетворення стрінги до намбера, 5 строго не дорівнює 6, тому - false

true + false // неявне приведення до намберів - 1

'4px' - 3 // підозрюю, що стрінг 4px не може неявно перетворитись на намбер, тому стрінг мінус намбер дає нелогічну дію - NaN

'4' - 3 // стрінг до намбера і різниця - 1

'6' + 3 ** 0; // пріорітет оператора приведення до степені, потім стрінг плюс 3 дає конкатенацію - 61, хоча з мінусом стрігш би привівся до намбера

12 / '6' // стірнг приводиться до намберу - 2

'10' + (5 === 6); //пріорітет виконання - порівння в дужках, арифметичні; дужки дають false, false приводться до стрінги і далі конкатенується з першо стрінгою - 10false

null == '' // нал при рівнянні дорівнює тільки собі або андефайнд - false

3 ** (9 / 3); //дужки, потім приведення в степінь - 27

!!'false' == !!'true' // хітро, дві стрінги приводяться до логічного значення оператором подвійного заперечення, обидві будуть тру, тру дорівнює тру - true

0 || '0' && 1 // пріорітет операторів - спочатку І потім АБО, стрінг 0 повертає тру, виконується права частина з намбер 1 (аутпут 1), далі 0 повертає фолс - виконуєтья права частина 1 тру - true

(+null == false) < 1; // пріорітет за дужками, унарний плюс з нал дає намбер 0, 0 порівнюється з приведеним фолс до намбера 0, 0 == 0 - true, при порівнянні з 1 тру приводиться до намберу 1, 1 < 1 - false

false && true || true // пріорітет І, виконується І - фолс дає фолс, права частина не виконується - виходимо з аутпутом false - виконується АБО - виводиться значення true

false && (false || true);  // дужки, в дужках тру, фолс І тру - дає false
 
(+null == false) < 1 ** 5; //дужки, в дужка унарний плюс нал до намбера - 0 - ноль нестрого дорівнєю фолс - true - 1 в ступені 5 - 1 - і тру < 1 - false